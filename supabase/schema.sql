-- SIPERPUS complete PostgreSQL schema for the current HTML client.
-- Safe to run on a new Supabase project. For an existing database, this adds
-- missing columns and constraints without dropping application data.
-- Run in Supabase SQL Editor as the project owner.
--
-- SECURITY: the current HTML authenticates against public.users using a
-- plaintext password. That is not safe for production. This schema enables
-- RLS and denies anonymous access. The frontend must be migrated to Supabase
-- Auth and set app_metadata.role to super_admin/admin/petugas before the
-- authenticated policies below will allow access. Never put service_role keys
-- in browser code and never add unrestricted anon policies.

begin;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null,
  password text not null default '', -- temporary compatibility only; remove after Supabase Auth migration
  role text not null default 'petugas',
  created_at timestamptz not null default now()
);

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  kode_barcode text not null,
  judul text not null,
  pengarang text not null default '',
  penerbit text not null default '',
  tahun_terbit integer,
  stok integer not null default 0,
  kategori text not null default 'Fiksi',
  katalog text not null default '',
  nomor_rak text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  nomor_anggota text not null,
  nama_lengkap text not null,
  tipe_anggota text not null default 'Siswa',
  created_at timestamptz not null default now()
);

create table if not exists public.procurements (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on update cascade on delete restrict,
  sumber_asal text not null default 'Dana BOS',
  kondisi text not null default 'Baru',
  tanggal_diterima date not null default current_date,
  jumlah integer not null default 1,
  created_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on update cascade on delete restrict,
  member_id bigint not null references public.members(id) on update cascade on delete restrict,
  user_id bigint references public.users(id) on update cascade on delete set null,
  tanggal_pinjam date not null default current_date,
  batas_kembali date not null,
  status text not null default 'Dipinjam',
  tanggal_dikembalikan date,
  created_at timestamptz not null default now()
);

-- Upgrade older installations by adding columns introduced/used by index.html.
alter table public.users
  add column if not exists username text,
  add column if not exists password text not null default '',
  add column if not exists role text not null default 'petugas',
  add column if not exists created_at timestamptz not null default now();

alter table public.books
  add column if not exists kode_barcode text,
  add column if not exists judul text,
  add column if not exists pengarang text not null default '',
  add column if not exists penerbit text not null default '',
  add column if not exists tahun_terbit integer,
  add column if not exists stok integer not null default 0,
  add column if not exists kategori text not null default 'Fiksi',
  add column if not exists katalog text not null default '',
  add column if not exists nomor_rak text not null default '',
  add column if not exists created_at timestamptz not null default now();

alter table public.members
  add column if not exists nomor_anggota text,
  add column if not exists nama_lengkap text,
  add column if not exists tipe_anggota text not null default 'Siswa',
  add column if not exists created_at timestamptz not null default now();

alter table public.procurements
  add column if not exists book_id bigint,
  add column if not exists sumber_asal text not null default 'Dana BOS',
  add column if not exists kondisi text not null default 'Baru',
  add column if not exists tanggal_diterima date not null default current_date,
  add column if not exists jumlah integer not null default 1,
  add column if not exists created_at timestamptz not null default now();

alter table public.transactions
  add column if not exists book_id bigint,
  add column if not exists member_id bigint,
  add column if not exists user_id bigint,
  add column if not exists tanggal_pinjam date not null default current_date,
  add column if not exists batas_kembali date,
  add column if not exists status text not null default 'Dipinjam',
  add column if not exists tanggal_dikembalikan date,
  add column if not exists created_at timestamptz not null default now();

-- Make sure identity-backed IDs exist for tables that may have been created earlier.
-- Existing primary keys and ID types are preserved; foreign key columns are expected to be bigint.

-- Add check constraints once. Existing invalid values should be corrected before this script.
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'users_role_allowed') then
    alter table public.users add constraint users_role_allowed check (role in ('super_admin','admin','petugas'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'books_stok_nonnegative') then
    alter table public.books add constraint books_stok_nonnegative check (stok >= 0);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'procurements_jumlah_positive') then
    alter table public.procurements add constraint procurements_jumlah_positive check (jumlah > 0);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'transactions_status_allowed') then
    alter table public.transactions add constraint transactions_status_allowed check (status in ('Dipinjam','Dikembalikan','Hilang'));
  end if;
end $$;

-- Foreign keys are explicit so PostgREST embedded selects used by the app resolve.
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'procurements_book_id_fkey') then
    alter table public.procurements add constraint procurements_book_id_fkey
      foreign key (book_id) references public.books(id) on update cascade on delete restrict;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'transactions_book_id_fkey') then
    alter table public.transactions add constraint transactions_book_id_fkey
      foreign key (book_id) references public.books(id) on update cascade on delete restrict;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'transactions_member_id_fkey') then
    alter table public.transactions add constraint transactions_member_id_fkey
      foreign key (member_id) references public.members(id) on update cascade on delete restrict;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'transactions_user_id_fkey') then
    alter table public.transactions add constraint transactions_user_id_fkey
      foreign key (user_id) references public.users(id) on update cascade on delete set null;
  end if;
end $$;

-- Unique identifiers and indexes supporting the HTML search/order patterns.
create unique index if not exists users_username_unique_idx on public.users (username) where username is not null;
create unique index if not exists books_kode_barcode_unique_idx on public.books (kode_barcode) where kode_barcode is not null;
create unique index if not exists members_nomor_anggota_unique_idx on public.members (nomor_anggota) where nomor_anggota is not null;
create index if not exists books_created_at_idx on public.books (created_at desc);
create index if not exists books_judul_idx on public.books (judul);
create index if not exists books_kategori_idx on public.books (kategori);
create index if not exists books_katalog_idx on public.books (katalog);
create index if not exists books_nomor_rak_idx on public.books (nomor_rak);
create index if not exists members_created_at_idx on public.members (created_at desc);
create index if not exists procurements_created_at_idx on public.procurements (created_at desc);
create index if not exists procurements_book_id_idx on public.procurements (book_id);
create index if not exists transactions_created_at_idx on public.transactions (created_at desc);
create index if not exists transactions_book_id_idx on public.transactions (book_id);
create index if not exists transactions_member_id_idx on public.transactions (member_id);
create index if not exists transactions_user_id_idx on public.transactions (user_id);
create index if not exists transactions_status_idx on public.transactions (status);

-- Default-deny database access. Policies require a Supabase Auth JWT with a
-- server-managed app_metadata.role claim (not user-editable user_metadata).
alter table public.users enable row level security;
alter table public.books enable row level security;
alter table public.members enable row level security;
alter table public.procurements enable row level security;
alter table public.transactions enable row level security;

revoke all on table public.users, public.books, public.members, public.procurements, public.transactions from anon;
grant select, insert, update, delete on table public.users, public.books, public.members, public.procurements, public.transactions to authenticated;

do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='books' and policyname='staff_manage_books') then
    create policy staff_manage_books on public.books for all to authenticated
      using ((auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin','admin','petugas'))
      with check ((auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin','admin','petugas'));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='members' and policyname='staff_manage_members') then
    create policy staff_manage_members on public.members for all to authenticated
      using ((auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin','admin','petugas'))
      with check ((auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin','admin','petugas'));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='procurements' and policyname='admins_manage_procurements') then
    create policy admins_manage_procurements on public.procurements for all to authenticated
      using ((auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin','admin'))
      with check ((auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin','admin'));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='transactions' and policyname='staff_manage_transactions') then
    create policy staff_manage_transactions on public.transactions for all to authenticated
      using ((auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin','admin','petugas'))
      with check ((auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin','admin','petugas'));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='users' and policyname='superadmins_manage_users') then
    create policy superadmins_manage_users on public.users for all to authenticated
      using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'super_admin')
      with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'super_admin');
  end if;
end $$;

commit;

